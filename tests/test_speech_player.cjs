const fs = require('node:fs');
const vm = require('node:vm');
const assert = require('node:assert/strict');
const events = [], played = [], notices = [];
const ctx = {CustomEvent: class {constructor(type, options) {this.type=type;this.detail=options.detail;}}, Quasar:{Notify:{create: x=>notices.push(x)}}};
vm.createContext(ctx);
vm.runInContext(fs.readFileSync('assets/speech-test.js','utf8'),ctx);
const audio={dataset:{}, pause(){}, play(){played.push(this.src);return Promise.resolve();}, dispatchEvent(e){events.push(e.detail);}};
const label={textContent:''}, button={querySelector:()=>label};
ctx.queueRecognitionSpeech(audio,'rat');
ctx.queueRecognitionSpeech(audio,'ox');
ctx.queueRecognitionSpeech(audio,'tiger');
assert.deepEqual(played,['rat','ox','tiger']);
audio.onended();
assert.equal(audio._speechBusy,false);
ctx.queueRecognitionSpeech(audio,'dog');
ctx.queueRecognitionSpeech(audio,'pig');
ctx.stopRecognitionSpeech(audio);
assert.equal(audio._pendingSpeech,null);
assert.equal(audio.onended,null);
ctx.toggleSpeechTest(button,audio,[['rat','鼠'],['ox','牛']]);
ctx.queueRecognitionSpeech(audio,'ignored');
assert.equal(audio._pendingSpeech,null);
assert.equal(events.at(-1),'rat');
audio.onended();
assert.equal(events.at(-1),'ox');
audio.onended();
assert.equal(events.at(-1),null);
assert.equal(audio.dataset.testing,undefined);
ctx.toggleSpeechTest(button,audio,[['rat','鼠']]);
ctx.toggleSpeechTest(button,audio,[['rat','鼠']]);
assert.equal(events.at(-1),null);
console.log('Speech interruption, mute, test synchronization and stop checks passed');
